function getAuAuthors(au) {
    const authors = Array.isArray(au.authors) ? au.authors : [au.author];
    return authors.flatMap(author => {
        if (!author) return [];
        const names = String(author.name || "").split(/\s+e\s+/i);
        const displays = String(author.display || author.name || "").split(/\s+e\s+/i);
        if (names.length > 1 && names.length === displays.length) {
            return names.map((name, index) => ({
                name: name.trim(),
                display: displays[index].trim()
            }));
        }
        return [{ name: author.name || author.display, display: author.display || author.name }];
    });
}
